{
  const lines = ['# Ubon', '', '> Ubon checks the work of coding agents. It runs in agent hooks (Claude Code, Codex, Cursor, Gemini CLI, GitHub Copilot), git hooks, and CI, and reports leaked secrets, trust-boundary bugs, missing data access policies, risky packages and commands, and weakened tests. It is deterministic and local.', ''];
  lines.push('Run `npx ubon check` to check the changes since the base branch. Exit code 1 means there is a `block` finding. Fix every `block` finding before you finish a task; `ubon explain <rule>` shows how.', '');
  lines.push('## Docs', '');
  for (const [path, title, description] of DOCS) lines.push(`- [${title}](${BLOB}/${path}): ${description}`);
  lines.push('', '## Rules', '');
  for (const rule of RULES) lines.push(`- [${rule.meta.id}](${BLOB}/docs/rules/${rule.meta.id}.md): ${rule.meta.title} (${rule.meta.level}).`);
  lines.push('', '## Optional', '', `- [Full text of the docs](${BLOB}/llms-full.txt): every page above in one file.`, `- [Changelog](${BLOB}/CHANGELOG.md)`, '');
  outputs.set('llms.txt', lines.join('\n'));
}

{
  const parts = [];
  const pages = [...DOCS.map(([p]) => p), 'docs/rules/README.md', ...RULES.map((r) => `docs/rules/${r.meta.id}.md`)];
  for (const page of pages) {
    const text = outputs.get(page) ?? (existsSync(join(root, page)) ? readFileSync(join(root, page), 'utf8') : null);
    if (text === null) continue;
    parts.push(`<!-- ${page} -->\n\n${text.replace(`${GENERATED}\n\n`, '').trim()}\n`);
  }
  outputs.set('llms-full.txt', parts.join('\n'));
}

// ---------------------------------------------------------------------------
// Write or compare

let stale = 0;
const expectedRulePages = new Set([...outputs.keys()].filter((p) => p.startsWith('docs/rules/')));
if (existsSync(join(root, 'docs/rules'))) {
  for (const file of listFilesRecursive(join(root, 'docs/rules'))) {
    const path = `docs/rules/${file}`;
    if (!expectedRulePages.has(path)) {
      if (check) {
        console.error(`gen-docs: ${path} has no rule; delete it or run npm run gen`);
        stale++;
      } else rmSync(join(root, path));
    }
  }
}
for (const [path, content] of outputs) {
  const full = join(root, path);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : null;
  if (current === content) continue;
  if (check) {
    console.error(`gen-docs: ${path} is out of date; run npm run gen`);
    stale++;
    continue;
  }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  console.log(`gen-docs: wrote ${path}`);
}
if (!check) removeEmptyDirs(join(root, 'docs/rules'));
if (check && stale > 0) process.exit(1);
if (check) console.log(`gen-docs: ${outputs.size} files up to date`);

function removeEmptyDirs(dir) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      removeEmptyDirs(full);
      if (readdirSync(full).length === 0) rmSync(full, { recursive: true });
    }
  }
}
