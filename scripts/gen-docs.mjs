const TOUR_PACKAGE = '{ "name": "ubon-tour", "private": true, "dependencies": { "next": "16.0.0" } }';
const TOUR_ROUTE = `import type { NextRequest } from 'next/server';

export async function GET(request: NextRequest) {
  const target = request.nextUrl.searchParams.get('url') ?? '';
  const page = await fetch(target);
  return new Response(await page.text(), { headers: { 'content-type': 'text/plain' } });
}
`;
const TOUR_FIXED = `import type { NextRequest } from 'next/server';

const ALLOWED_HOSTS = new Set(['example.com', 'www.example.com']);

export async function GET(request: NextRequest) {
  const raw = request.nextUrl.searchParams.get('url') ?? '';
  const target = URL.canParse(raw) ? new URL(raw) : null;
  if (!target || target.protocol !== 'https:' || !ALLOWED_HOSTS.has(target.hostname)) {
    return new Response('URL not allowed', { status: 400 });
  }
  const page = await fetch(target);
  return new Response(await page.text(), { headers: { 'content-type': 'text/plain' } });
}
`;
const TOUR_START = '{"session_id":"tour","hook_event_name":"SessionStart","source":"startup"}';
const TOUR_STOP = '{"session_id":"tour","hook_event_name":"Stop"}';

async function tourOutputs() {
  const { initRepo, commitAll, tempDir } = await import('../test/support/fixtures.ts');
  const { memoryIO } = await import('../test/support/io.ts');
  const { main } = await import('../src/cli/main.ts');
  const work = tempDir('ubon-tour-');
  const dir = join(work, 'ubon-tour');
  const run = async (args, stdin = '') => {
    const io = memoryIO(dir, stdin);
    const code = await main(args, io);
    if (io.err) throw new Error(`gen-docs: \`ubon ${args.join(' ')}\` in the tutorial wrote to stderr: ${io.err}`);
    // Elapsed times differ between runs.
    return { code, out: io.out.replace(/ \(\d+(?:\.\d+)? s\)$/gm, '') };
  };
  const expect = (ok, what) => {
    if (!ok) throw new Error(`gen-docs: the tutorial no longer works: ${what}`);
  };
  try {
    mkdirSync(join(dir, 'app/api/preview'), { recursive: true });
    initRepo(dir);
    writeFileSync(join(dir, 'package.json'), `${TOUR_PACKAGE}\n`);
    commitAll(dir, 'Start');
    const init = await run(['init', '--claude', '--yes']);
    expect(init.code === 0, 'ubon init --claude --yes failed');
    commitAll(dir, 'Set up Ubon');
    const start = await run(['hook', 'claude', 'SessionStart'], TOUR_START);
    writeFileSync(join(dir, 'app/api/preview/route.ts'), TOUR_ROUTE);
    const stop = await run(['hook', 'claude', 'Stop'], TOUR_STOP);
    const decision = JSON.parse(stop.out || '{}');
    expect(decision.decision === 'block' && typeof decision.reason === 'string', 'the Stop hook did not block');
    const check = await run(['check']);
    expect(check.code === 1, `ubon check exited with ${check.code}, not 1`);
    writeFileSync(join(dir, 'app/api/preview/route.ts'), TOUR_FIXED);
    const fixed = await run(['check']);
    expect(fixed.code === 0, `ubon check on the fixed route exited with ${fixed.code}:\n${fixed.out}`);
    const stopAgain = await run(['hook', 'claude', 'Stop'], TOUR_STOP);
    expect(stopAgain.code === 0 && stopAgain.out === '', 'the Stop hook still blocks after the fix');
    return { init, start, stop, reason: decision.reason, check, fixed };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

