function refLinks(meta) {
  const out = [];
  for (const cwe of meta.cwe ?? []) {
    const n = /CWE-(\d+)/.exec(cwe)?.[1];
    out.push(n ? `[${cwe}](https://cwe.mitre.org/data/definitions/${n}.html)` : cwe);
  }
  for (const o of meta.owasp ?? []) out.push(`OWASP ${o}`);
  for (const r of meta.references ?? []) out.push(r.startsWith('http') ? `<${r}>` : r);
  return out;
}

function rulePage(rule, examples) {
  const m = rule.meta;
  const lines = [GENERATED, '', `# ${m.id}`, '', `${m.title}.`, '', m.summary, ''];
  lines.push(`- Default level: \`${m.level}\`.`);
  if (m.levels) lines.push(`- Levels: ${m.levels.replace(/\.$/, '')}.`);
  lines.push(`- Looks at: ${SCOPES[m.scope] ?? m.scope}.`);
  const refs = refLinks(m);
  if (refs.length > 0) lines.push(`- References: ${refs.join(', ')}.`);
  lines.push('', '## Why it matters', '', m.why, '');
  if (examples.flagged.length > 0) {
    lines.push('## Flagged', '');
    for (const e of examples.flagged.slice(0, 8)) {
      lines.push(`\`${e.file}\`${e.level ? ` (${e.level})` : ''}:`, '', `\`\`\`${fenceLang(e.file)}`, e.code, '```', '');
    }
  }
  if (examples.safe.length > 0) {
    lines.push('## Not flagged', '');
    for (const e of examples.safe.slice(0, 10)) {
      if (e.code) lines.push(`- \`${e.code.replace(/`/g, "'")}\` in \`${e.file}\`: ${e.note}`);
      else lines.push(`- ${e.note}`);
    }
    lines.push('');
  }
  lines.push('## How to fix', '', m.fix, '');
  if (m.scope !== 'hook') {
    lines.push(
      '## If the finding is wrong',
      '',
      'Add a comment on the line above, in the comment syntax of the file, that says who decided and why:',
      '',
      '```',
      `ubon-ignore ${m.id}: <who decided>: <evidence>`,
      '```',
      '',
      `Or turn the rule off for the project in \`ubon.json\`: \`"rules": { "${m.id}": "off" }\`. See [configuration](../../config.md).`,
      '',
    );
  } else {
    lines.push('## If the check is wrong', '', `This check runs in agent hooks. Allow a command prefix with \`commands.allow\` in \`ubon.json\`, or set \`"rules": { "${m.id}": "off" }\`. See [configuration](../../config.md).`, '');
  }
  if (existsSync(join(root, 'fixtures/rules', m.id))) lines.push(`Fixtures: [fixtures/rules/${m.id}](../../../fixtures/rules/${m.id}).`, '');
  return lines.join('\n');
}

const examplesById = {};
const byPack = new Map();
for (const rule of RULES) {
  const id = rule.meta.id;
  const examples = collectExamples(id);
  examplesById[id] = examples;
  const [pack] = id.split('/');
  if (!byPack.has(pack)) byPack.set(pack, []);
  byPack.get(pack).push(rule);
  outputs.set(`docs/rules/${id}.md`, rulePage(rule, examples));
}

