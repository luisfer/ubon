// README demo: `ubon check` on fixtures/demo (before/ is the base commit, after/ the agent's changes)

async function demoOutput() {
  const { initRepo, commitAll, copyTree, replaceTree, tempDir, git } = await import('../test/support/fixtures.ts');
  const { expandFakeKeysInDir } = await import('../test/support/fake-keys.ts');
  const { runCheck } = await import('../src/core/engine.ts');
  const { formatText } = await import('../src/report/text.ts');
  const work = tempDir('ubon-demo-');
  try {
    initRepo(work);
    copyTree(join(root, 'fixtures/demo/before'), work);
    expandFakeKeysInDir(work);
    commitAll(work, 'base');
    git(work, 'checkout', '-q', '-b', 'agent-work');
    replaceTree(work, join(root, 'fixtures/demo/after'));
    expandFakeKeysInDir(work);
    const { report } = await runCheck({ cwd: work, mode: 'diff', useBaseline: false });
    const text = formatText(report, { color: false });
    const code = report.summary.block > 0 ? 1 : 0;
    return { text, code };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

{
  const readme = readFileSync(join(root, 'README.md'), 'utf8');
  const begin = '<!-- ubon:demo:begin -->';
  const end = '<!-- ubon:demo:end -->';
  const a = readme.indexOf(begin);
  const b = readme.indexOf(end);
  if (a !== -1 && b > a && existsSync(join(root, 'fixtures/demo/after'))) {
    const { text, code } = await demoOutput();
    const why = code === 1 ? 'because there are blocking findings' : 'because there are no blocking findings';
    const block = `${begin}\n\`\`\`text\n$ npx ubon check\n${text.trimEnd()}\n\`\`\`\n\nThe exit code is ${code} ${why}. This output is generated from [fixtures/demo](fixtures/demo), where \`before/\` is the base commit and \`after/\` is what an agent changed.\n${end}`;
    outputs.set('README.md', `${readme.slice(0, a)}${block}${readme.slice(b + end.length)}`);
  }
}

